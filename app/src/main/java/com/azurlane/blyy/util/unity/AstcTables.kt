/**
 * ASTC 软件解码用的常量表（**由参考实现的 C 源码逐字节提取，请勿手改**）。
 *
 * 只需要两张表：
 * - [TRITS]：5 个 trit（三进制位）打包进 8 bit 后的展开表（`5 x 256`）；
 * - [QUINTS]：3 个 quint（五进制位）打包进 7 bit 后的展开表（`3 x 128`）。
 *
 * 历史上的解码器把这 1664 个整数直接写成字面量数组（约 12KB 源码、极易抄错）；
 * 这里改成「一个字符一个数字」的紧凑字符串，运行时解析成 IntArray：
 * 源码体积降到 2KB 以内，且生成脚本保证与参考实现逐字节一致。
 *
 * 数据来源：Texture2DDecoder (MIT) `astc.cpp` 的 `TritsTable` / `QuintsTable`
 * —— 与 UnityPy / AssetStudio 使用的 ASTC 解码实现同源。
 */
internal object AstcTables {

    /** 5 trits（每个 0..2）打包成 8 bit 的展开表：`[元素下标][打包值] = trit` */
    val TRITS: Array<IntArray> = parse(rows = 5, columns = 256, raw = TRITS_RAW)

    /** 3 quints（每个 0..4）打包成 7 bit 的展开表：`[元素下标][打包值] = quint` */
    val QUINTS: Array<IntArray> = parse(rows = 3, columns = 128, raw = QUINTS_RAW)

    /** 8 bit 位反转表（ASTC 反向整数序列要用），运行时生成，省掉 256 个字面量 */
    val BIT_REVERSE: IntArray = IntArray(256) { value ->
        var input = value
        var output = 0
        repeat(8) {
            output = (output shl 1) or (input and 1)
            input = input ushr 1
        }
        output
    }

    private fun parse(rows: Int, columns: Int, raw: String): Array<IntArray> {
        require(raw.length == rows * columns) {
            "ASTC 常量表长度不符：期望 ${'$'}{rows * columns}，实际 ${'$'}{raw.length}"
        }
        var cursor = 0
        return Array(rows) { IntArray(columns) { raw[cursor++] - '0' } }
    }

